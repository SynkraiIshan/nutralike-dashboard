export function getPackWeightOptions(
  type: keyof typeof MOCK_PACKAGING_MATERIALS
): { value: string; label: string }[] {
  const weights = Object.keys(MOCK_PACKAGING_MATERIALS[type] ?? {});
  return weights
    .sort((a, b) => parseInt(a, 10) - parseInt(b, 10))
    .map((w) => ({ value: w, label: w }));
}

export function formatSettingKey(key: string): string {
  return key.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
}

export function parsePackWeightGrams(packWeight: string): number {
  return parseInt(packWeight.replace(/\D/g, ''), 10) || 0;
}
